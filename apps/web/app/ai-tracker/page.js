"use client";

import { Suspense, useCallback, useState } from "react";
import { usePathname, useRouter, useSearchParams } from "next/navigation";
import { PortalShell } from "@/components/auth/portal-shell";
import { useSession } from "@/components/auth/session-provider";
import { PageHeader } from "@/components/layout";
import { Tabs } from "@/components/ui";
import { MyReportsTab } from "@/components/ai-tracker/my-reports-tab";
import { TeamReportsTab } from "@/components/ai-tracker/team-reports-tab";
import { PdfViewer } from "@/components/ai-tracker/pdf-viewer";
import { apiBlob } from "@/lib/api";
import { canAnywhere } from "@/lib/can";
import { monthLabel } from "@/lib/format";

const USAGE_PERMS = ["ai.usage.manage:own", "ai.usage.view"];

function ClaudeUsage() {
  const router = useRouter();
  const pathname = usePathname();
  const params = useSearchParams();
  const { me } = useSession();
  const [viewing, setViewing] = useState(null);

  // Tabs follow permissions: everyone who submits sees "My reports"; managers/admins also see "Team reports".
  const tabs = [
    ...(canAnywhere(me, "ai.usage.manage:own") ? [{ value: "mine", label: "My reports" }] : []),
    ...(canAnywhere(me, "ai.usage.view") ? [{ value: "team", label: "Team reports" }] : []),
  ];
  const tab = tabs.some((t) => t.value === params.get("tab")) ? params.get("tab") : tabs[0]?.value;
  const onView = useCallback((report, owner) => setViewing({ report, owner }), []);
  const closeViewer = useCallback(() => setViewing(null), []);
  const load = useCallback(() => apiBlob(`/ai/usage-reports/${viewing?.report.id}/file`), [viewing]);

  return (
    <>
      <PageHeader
        title="Claude usage reports"
        description="A monthly executive report on how each person uses Claude — generated by a Claude skill, uploaded as a PDF."
        actions={tabs.length > 1 && <Tabs aria-label="Report views" tabs={tabs} value={tab} onChange={(v) => router.replace(`${pathname}?tab=${v}`)} />}
      />
      {tab === "mine" && <MyReportsTab onView={onView} />}
      {tab === "team" && <TeamReportsTab onView={onView} />}
      <PdfViewer
        open={!!viewing}
        onClose={closeViewer}
        load={load}
        title={viewing ? `${viewing.owner} · ${monthLabel(viewing.report.period)}` : ""}
        subtitle={viewing?.report.fileName}
        fileName={viewing?.report.fileName}
      />
    </>
  );
}

export default function AiTrackerPage() {
  return (
    <PortalShell requires={USAGE_PERMS} breadcrumbs={[{ label: "Home", href: "/" }, { label: "AI Tracker" }]}>
      <Suspense>
        <ClaudeUsage />
      </Suspense>
    </PortalShell>
  );
}
